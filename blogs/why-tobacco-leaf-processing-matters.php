                    <p class="article-lead">
                        Tobacco is an agricultural product, but producing a high-quality tobacco leaf is only one part of the larger tobacco value chain. Once harvested and cured, tobacco leaf must be handled, conditioned, processed, threshed, separated, dried, inspected and packed with precision.
                    </p>

                    <p class="article-paragraph">
                        This is where tobacco leaf processing becomes critical. Modern tobacco processing is designed to transform cured tobacco leaf into a consistent, controlled and usable material while preserving important characteristics of the leaf. For industrial processors, the objective is not simply to move tobacco through a processing line. It is to manage the material carefully at every stage.
                    </p>

                    <div class="article-callout">
                        <div class="article-callout-title">Core Operating Principle</div>
                        <p class="no-margin" style="font-family: Montserrat, sans-serif; font-size: 17px; color: #fff; font-weight: 500;">
                            Advanced Processing. Proven Capability. Consistent Quality.
                        </p>
