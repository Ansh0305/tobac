                        </div>
                        <p class="article-paragraph" style="margin-bottom: 0; font-size: 14.5px; opacity: 0.85;">
                            Lower-position materials such as primings and lugs are systematically classified, confirming that different parts of the plant offer distinct processing qualities.
                        </p>
                    </div>

                    <!-- NLS FCV -->
                    <div class="grade-category-box">
                        <div class="grade-category-title">3. NLS FCV Tobacco</div>
                        <p class="article-paragraph" style="margin-bottom: 12px;">
                            Northern Light Soils (NLS) FCV tobacco is renowned for its distinctive body, style and chemical characteristics. Grades such as NCX1O and NCX2O describe lugs and cutters with lemon orange, orange and deep orange profiles.
                        </p>
                        <div class="grade-codes-list">
                            <span class="grade-code-chip">NCX1O</span>
                            <span class="grade-code-chip">NCX2O</span>
                            <span class="grade-code-chip">NL Grades (Oily, Ripe, Mature)</span>
                            <span class="grade-code-chip">NX4O, NX5O, NX6O, NX7O</span>
                        </div>
                        <p class="article-paragraph" style="margin-bottom: 0; font-size: 14.5px; opacity: 0.85;">
                            NL grades represent leaf materials with oily texture and full maturity, complemented by lower-position NX grades.
                        </p>
                    </div>

