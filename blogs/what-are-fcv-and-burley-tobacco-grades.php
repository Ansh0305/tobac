                            <span class="grade-code-chip">ML2O</span>
                            <span class="grade-code-chip">ML4O</span>
                            <span class="grade-code-chip">MX &amp; ML classifications</span>
                        </div>
                        <p class="article-paragraph" style="margin-bottom: 0; font-size: 14.5px; opacity: 0.85;">
                            The catalogue provides specific indicative nicotine and sugar ranges for each grade in this category.
                        </p>
                    </div>

                    <!-- Traditional FCV -->
                    <div class="grade-category-box">
                        <div class="grade-category-title">2. Traditional FCV Tobacco (TRAD FCV)</div>
                        <p class="article-paragraph" style="margin-bottom: 12px;">
                            Traditional FCV represents another vital category within Indian tobacco production. Grades in this category include leaf and cutter materials with characteristics ranging from lemon orange to vibrant orange and rich deep orange.
                        </p>
                        <p class="article-paragraph" style="margin-bottom: 12px;">
                            The catalogue reflects clear distinctions between ripe, mature and unripe leaf:
                        </p>
                        <div class="grade-codes-list">
