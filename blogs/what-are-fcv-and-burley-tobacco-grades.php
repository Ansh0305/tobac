                    <p class="article-lead">
                        Tobacco is not a single uniform agricultural product. Different varieties, growing regions, leaf positions, maturity levels and curing characteristics can result in significantly different tobacco grades.
                    </p>

                    <p class="article-paragraph">
                        For businesses involved in tobacco leaf processing, understanding these differences is essential. Grade classification helps describe the characteristics of tobacco leaf and provides a common reference for buyers, processors and other participants in the tobacco value chain.
                    </p>

                    <p class="article-paragraph">
                        At Tabac Leaf Enterprises, our <strong>Tobacco Grade Catalogue</strong> brings together an extensive range of grades across Mysore FCV, Traditional FCV, NLS FCV and Vinukonda Burley.
                    </p>

                    <h2 class="article-heading">What Does a Tobacco Grade Tell Us?</h2>
                    <p class="article-paragraph">
                        A tobacco grade is a structured method of describing particular physical, visual and chemical characteristics of processed or unprocessed tobacco leaf. Depending on the variety and grading framework, descriptions consider:
                    </p>

                    <ul style="color: rgba(255, 255, 255, 0.82); line-height: 2; margin-bottom: 24px; padding-left: 24px;">
                        <li><strong>Leaf Position &amp; Type:</strong> Primings, lugs, cutters, and leaf positions</li>
                        <li><strong>Visual Characteristics:</strong> Lemon orange, orange, deep orange, tan, and dark colour profiles</li>
                        <li><strong>Body &amp; Maturity:</strong> Ripe, mature, immature, oily, and heavy-bodied leaf</li>
                        <li><strong>Quality Category:</strong> First choice, standard, and lower-stalk material</li>
                        <li><strong>Processing Characteristics:</strong> Threshability, lamina yield, and moisture behaviour</li>
                        <li><strong>Chemical Composition:</strong> Indicative nicotine ranges and sugar ranges</li>
                        <li><strong>Packing Format:</strong> Bales, cartons, and moisture-controlled packaging</li>
                    </ul>

                    <p class="article-paragraph">
                        A tobacco grade catalogue therefore serves as much more than a list of product codes. It provides an authoritative technical reference for understanding the characteristics associated with different industrial materials.
                    </p>

                    <!-- Mysore FCV -->
                    <div class="grade-category-box">
                        <div class="grade-category-title">1. Mysore FCV Tobacco</div>
                        <p class="article-paragraph" style="margin-bottom: 12px;">
                            Mysore FCV is one of the premier categories represented in the Tabac Leaf Enterprises catalogue. Mysore FCV grades include different combinations of lugs, cutters, leaf and primings, with descriptions referring to characteristics such as lemon orange, orange, deep orange and brown colour profiles.
                        </p>
                        <p class="article-paragraph" style="margin-bottom: 12px;">
                            The catalogue distinguishes carefully between ripe, mature and immature tobacco to support exact blending profiles:
                        </p>
                        <div class="grade-codes-list">
                            <span class="grade-code-chip">MCX1O</span>
                            <span class="grade-code-chip">MCX23O</span>
