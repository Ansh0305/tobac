                    <div class="grade-category-box">
                        <div class="grade-category-title">4. Vinukonda Burley Tobacco</div>
                        <p class="article-paragraph" style="margin-bottom: 12px;">
                            Burley tobacco has fundamental characteristics that distinguish it from Flue-Cured Virginia (FCV) categories. It undergoes air-curing rather than flue-curing, resulting in distinct physical and chemical attributes.
                        </p>
                        <div class="grade-codes-list">
                            <span class="grade-code-chip">VBL1F</span>
