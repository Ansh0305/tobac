                function ensureFonts(theme) {
                    var fams = (theme && theme.googleFonts) || [];
                    // backward-compat: old configs with no googleFonts list but still using Fraunces
                    if (!fams.length && theme && /Fraunces/i.test((theme.fontHeading || "") + (theme.fontBody || "")))
                        fams = ["Fraunces:opsz,wght@9..144,300;9..144,400"];
                    if (!fams.length) return; // template's own font in use — nothing to load
                    var href =
                        "https://fonts.googleapis.com/css2?family=" +
                        fams
                            .map(function (f) {
                                return String(f).replace(/ /g, "+");
                            })
                            .join("&family=") +
                        "&display=swap";
                    var link = document.getElementById("rtVaultFonts");
                    if (link) {
                        if (link.getAttribute("href") !== href) link.setAttribute("href", href);
                        return;
                    }
                    link = document.createElement("link");
                    link.id = "rtVaultFonts";
                    link.rel = "stylesheet";
                    link.href = href;
                    document.head.appendChild(link);
                }
                function ensureCss() {
                    if (document.getElementById("rtVaultCss")) return;
                    var s = document.createElement("style");
                    s.id = "rtVaultCss";
                    s.textContent = CSS;
                    document.head.appendChild(s);
