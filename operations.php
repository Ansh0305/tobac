                function md(s) {
                    return String(s == null ? "" : s)
                        .replace(/~~([^~]+)~~/g, "<s>$1</s>")
                        .replace(/\*\*([^*]+)\*\*/g, "<b>$1</b>")
                        .replace(/\n/g, "<br>");
