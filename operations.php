                // container is optional (defaults to body). opts.preview => inline, always-open, unwired.
                function render(cfg, container, opts) {
                    opts = opts || {};
                    cfg = merge(DEFAULTS, cfg || {});
                    ensureFonts(cfg.theme);
                    ensureCss();
                    var host = container || document.body;
                    if (opts.preview) host.innerHTML = "";
                    else if (document.querySelector(".rt-vlt-root")) return null; // mount once

                    var root = document.createElement("div");
                    root.className = "rt-vlt-root" + (opts.preview ? " rt-vlt-preview" : "");
                    applyTheme(root, cfg.theme);
                    root.innerHTML = buildHTML(cfg);
                    host.appendChild(root);

                    // broken thumbnails fall back to the faux card (no broken-image icons)
                    Array.prototype.forEach.call(root.querySelectorAll(".rt-vlt-shot--img img"), function (im) {
                        im.addEventListener("error", function () {
                            var shot = im.parentNode;
                            if (shot) shot.outerHTML = fauxShot(im.getAttribute("data-c") || "#8a8256");
                        });
                    });

                    var ov = root.querySelector("#rtVltOverlay");
                    if (opts.preview) {
                        ov.classList.add("open");
                        return root;
                    }

                    function show() {
                        ov.classList.add("open");
                        document.body.style.overflow = "hidden";
                    }
                    function hide() {
                        ov.classList.remove("open");
                        document.body.style.overflow = "";
                    }
                    root.querySelector("#rtVltOpen").addEventListener("click", show);
                    root.querySelector("#rtVltClose").addEventListener("click", hide);
                    ov.addEventListener("click", function (e) {
                        if (e.target === ov) hide();
                    });
                    document.addEventListener("keydown", function (e) {
                        if (e.key === "Escape") hide();
                    });
                    return root;
                }

